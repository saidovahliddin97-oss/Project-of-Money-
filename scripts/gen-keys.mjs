// Generates the license signing key pair.
//  - public key  -> public/assets/js/license-pubkey.js (committed, used by browsers)
//  - private key -> .secrets/license-private.jwk.json (git-ignored) and printed
//    once so you can paste it into the LICENSE_PRIVATE_JWK secret of your host.
// Re-running it invalidates every license issued with the old key, so it
// refuses to overwrite an existing key unless you pass --force.
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateKeyPair } from '../public/assets/js/core/license.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const secretFile = join(root, '.secrets', 'license-private.jwk.json');
if (existsSync(secretFile) && !process.argv.includes('--force')) {
  console.error(`${secretFile} already exists. Use --force to replace it (old licenses will stop working).`);
  process.exit(1);
}
const { privateJwk, publicJwk } = await generateKeyPair();
const pub = { kty: publicJwk.kty, crv: publicJwk.crv, x: publicJwk.x, y: publicJwk.y };
writeFileSync(
  join(root, 'public/assets/js/license-pubkey.js'),
  `// Generated by \`npm run keys\`. Public half of the license signing key (safe to publish).\nexport const LICENSE_PUBLIC_JWK = ${JSON.stringify(pub)};\n`,
);
mkdirSync(dirname(secretFile), { recursive: true });
writeFileSync(secretFile, JSON.stringify(privateJwk), { mode: 0o600 });
console.log('Public key written to public/assets/js/license-pubkey.js (commit it).');
console.log(`Private key saved to ${secretFile} (never commit it).`);
console.log('\nSet this value as the LICENSE_PRIVATE_JWK secret on Cloudflare/Vercel:\n');
console.log(JSON.stringify(privateJwk));
